/**
  * @brief This function handles DMA1 channel1 global interrupt.
  */
void DMA1_Channel1_IRQHandler(void)
{
  /* USER CODE BEGIN DMA1_Channel1_IRQn 0 */
  /* 这是 DMA 的硬件中断入口。HAL 负责解析标志、分发对应回调。
   * 本版在 current_sense.c 中关闭了 DMA 半满/全满通知，采样依旧由 DMA 持续搬运。
   * 电机的 1ms 控制更新走下方 TIM3 中断，不在这个 DMA 中断中安排。 */
  /* USER CODE END DMA1_Channel1_IRQn 0 */
  HAL_DMA_IRQHandler(&hdma_adc1);
  /* USER CODE BEGIN DMA1_Channel1_IRQn 1 */

  /* USER CODE END DMA1_Channel1_IRQn 1 */
}

/**
  * @brief This function handles TIM3 global interrupt.
  */
void TIM3_IRQHandler(void)
{
  /* USER CODE BEGIN TIM3_IRQn 0 */
  /* TIM3 每 1ms 更新后，CPU 从中断向量跳到这里。
   * 下方 HAL_TIM_IRQHandler(&htim3) 会处理更新标志并调用
   * 下方 USER CODE 1 中的 HAL_TIM_PeriodElapsedCallback(&htim3)，再转发给控制模块。
   * 不要把电机流程在这里和 HAL 回调中各调用一次，否则一次中断会更新两遍。 */
  /* USER CODE END TIM3_IRQn 0 */
  HAL_TIM_IRQHandler(&htim3);
  /* USER CODE BEGIN TIM3_IRQn 1 */

  /* USER CODE END TIM3_IRQn 1 */
}

/* USER CODE BEGIN 1 */
/* 中断入口只转发，不在这里堆放采样公式或电机动作流程。
 * TIM2 连续输出 20kHz PWM；这里只响应 TIM3 每 1ms 的控制更新。 */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM3)
  {
    MotorControl_Update1ms();
  }
}
